DETECTION_PROMPT = """You are reviewing two shots from a video project. These may be from a traditional film shoot or from AI-generated clips (Runway, Veo, Kling, Sora, Pika, or others).

You will see multiple frames per shot (typically 3 frames sampled at 25% / 50% / 75% of each shot's duration). Frames labelled "SHOT A" are the earlier shot — the reference. Frames labelled "SHOT B" are the shot under review.

Use multi-frame coverage to your advantage: an object or anomaly that appears in only SOME frames is a stronger signal than one visible in all frames.

---

There are four kinds of errors to look for:

1. STANDALONE ERRORS in Shot B — things wrong regardless of Shot A:
   - An anachronistic prop (e.g. a modern object in a historical setting)
   - Visible production equipment or crew in frame
   - Wardrobe that doesn't match the scene's established world

2. CROSS-SHOT CONTINUITY ERRORS — only if A and B show the same physical location/character from a different angle AND you can confirm it is the same scene moment:
   - A prop that was in one position in A and is noticeably different in B
   - A wardrobe item (button, collar, sleeve) that visibly changed between A and B
   - Hair or makeup that changed significantly between A and B

3. TEMPORAL/CAUSATION ERRORS — effects appearing before their causes:
   - Bullet holes, damage, blood, or broken glass visible in one shot, but the event causing them is shown in the other shot
   - A character holding an object in Shot A that wasn't picked up yet

4. AI CLIP CONSISTENCY ERRORS — flag when the two shots don't match in ways that make the cut feel broken. These are especially common when clips were generated by different AI models or at different times:
   - LIGHTING MISMATCH (type: "lighting"): Significantly different color temperature, overall exposure, or color grade between shots. E.g. Shot A is warm golden-hour and Shot B is cool overcast; one is high-contrast and the other is washed out. Flag these even if the shots have different camera angles — for video projects, consistent lighting across cuts is always a concern.
   - ATMOSPHERE MISMATCH (type: "atmosphere"): Different weather, time of day, season, or background environment. E.g. clear sunny sky vs storm clouds; summer greenery vs bare winter trees; noon light vs blue-hour dusk; desert landscape vs rocky shoreline — any case where the overall backdrop or environment of the scene changes dramatically across frames.
   - STYLE MISMATCH (type: "other"): The shots appear to come from visually incompatible styles — e.g. one is realistic and cinematic while the other looks clearly synthetic or over-processed; one has heavy film grain while the other is perfectly clean.

   For AI clip consistency errors:
   - object_query: phrase targeting the affected aspect — "lighting and color grade", "sky and atmosphere", "overall color temperature", "visual style"
   - fix_suggestion: a direct comparative instruction — e.g. "Regrade Shot B to match the warm golden-hour tone of Shot A" or "Change the sky in Shot B to match the clear conditions in Shot A"
   - fix_target_shot: "B" (Shot A is the reference; Shot B gets fixed)

---

Rules:
- DO NOT flag subtle lighting shifts clearly caused by camera angle (shadows from a different direction, natural exposure shift when pointing toward a window). DO flag significant mood or grade differences that would be noticeable on a cut.
- DO NOT flag both "atmosphere" and "lighting" for the same root cause. If a lighting mismatch is a direct consequence of an environment/atmosphere change (e.g. desert sunset → overcast shoreline makes everything warmer→cooler), flag it as "atmosphere" only. Only flag "lighting" independently if the environment is the same but the color grade or exposure differs.
- DO NOT flag action progression (characters moved naturally), extras repositioning, or intentional scene transitions.
- If A and B are clearly MEANT to be different scenes (an intentional narrative cut: flashback, time jump, cutaway to a different day or storyline), return {"errors": [], "different_scene": true}. IMPORTANT: for AI-generated footage, dramatically different backgrounds (desert vs. rocky shoreline, different weather, different time of day) within the same sequence are usually generation inconsistencies, NOT intentional cuts. If the shots share a subject (e.g. same character/astronaut), flag the background mismatch as an "atmosphere" error rather than returning different_scene: true.
- Without a user hint: 1–3 high-confidence errors is better than 8 uncertain ones.
- With a user hint at the top: trust it and flag what they described.

For each error return:
- type: one of [prop, wardrobe, lighting, hair, set_dressing, eyeline, atmosphere, other]
  * set_dressing = specific identifiable object/prop on the set changed (a vase moved, a lamp appeared). NOT for whole-background or environment changes — those are "atmosphere".
  * atmosphere = any whole-scene environment difference: weather, time of day, season, or a dramatically different backdrop/location.
- description: one sentence — what the problem is and which shot has it.
- fix_suggestion: ONE clean imperative sentence. No alternatives, no production notes.
- severity: low | medium | high
- object_query: SHORT noun phrase 2–5 words naming the target (e.g. "modern coffee cup", "lighting and color grade", "sky and atmosphere"). Required — fed to downstream localization.
- fix_target_shot: "A" or "B" — which shot needs fixing.
  * Standalone or cross-shot error in Shot B → "B"
  * Shot A is the wrong one (temporal error, etc.) → "A"
  * AI clip consistency error → "B" (A is the reference)

Do NOT output bounding boxes — a separate model handles localization.

Return STRICT JSON only:
{
  "different_scene": false,
  "errors": [
    { "type": "...", "description": "...", "fix_suggestion": "...", "severity": "...", "object_query": "...", "fix_target_shot": "A" or "B" }
  ]
}

If no errors: {"different_scene": false, "errors": []}"""


STANDALONE_PROMPT = """You are reviewing keyframes from a SINGLE SHOT of a film for things that don't belong in the scene's world.

Look at the frames carefully. Identify any STANDALONE errors visible in this shot:
- Anachronistic props (modern objects in historical settings — coffee cups, plastic bottles, smartphones, wristwatches, etc.)
- Visible production equipment (microphones, cameras, crew, light stands, reflections of crew)
- Wardrobe items that don't match the scene's established world
- Background/environment inconsistency WITHIN the shot: if the background changes dramatically across frames (e.g. frame 1 shows a desert at sunset, frame 3 shows a rocky shoreline — a dramatic environment shift within what should be a continuous shot), flag this as type "atmosphere"
- Anything else that clearly does NOT belong in the scene

For each error return:
- type: one of [prop, wardrobe, lighting, hair, set_dressing, eyeline, atmosphere, other]
  * set_dressing = a specific identifiable prop or object on the set that doesn't belong (a vase, a lamp, a piece of furniture). NOT for whole-background or environment changes.
  * atmosphere = the overall backdrop or environment changes dramatically across frames (e.g. desert to rocky shoreline, sunny sky to storm clouds, different time of day). Use this when the whole scene background shifts, not a specific object.
  * lighting = the overall color temperature, exposure, or grade changes significantly across frames.
- description: one sentence describing the error
- fix_suggestion: ONE clean imperative sentence (e.g. "Remove the coffee cup from the table"). For atmosphere/lighting errors, describe the whole-scene correction (e.g. "Match the background environment across all frames to the warm sunset desert").
- object_query: SHORT noun phrase 2–5 words naming the target. For atmosphere errors use "background environment" or "sky and landscape"; for lighting use "lighting and color grade".
- severity: low | medium | high

CRITICAL: you must VISUALLY CONFIRM the error in the frames before flagging. If you cannot see it in any frame, do not flag. Honest "I don't see it" beats confident hallucination.

Return STRICT JSON only:
{
  "errors": [
    { "type": "...", "description": "...", "fix_suggestion": "...", "object_query": "...", "severity": "..." }
  ]
}

If no errors: {"errors": []}"""


def build_standalone_prompt(user_hint: str = "") -> str:
    hint = (user_hint or "").strip()
    if not hint:
        return STANDALONE_PROMPT
    return (
        "USER HINT — the person who uploaded this footage said:\n"
        f'  "{hint}"\n\n'
        "How to use this hint:\n"
        "1. The hint tells you WHERE to look and WHAT KIND of error to search for.\n"
        "2. You must VISUALLY CONFIRM the error in the frames before flagging. The hint is a guide, NOT a guarantee.\n"
        "3. If the hint describes an error but the frames don't show it, return no errors. Honest 'I don't see it' beats hallucination.\n\n"
        + STANDALONE_PROMPT
    )


