HOLISTIC_PROMPT = """You are reviewing a sequence of clips from an AI video project. These clips should feel like one cohesive scene, but they may have been generated at different times or by different AI models.

Look at ALL shots together and identify any that stand out as inconsistent with the overall sequence — specifically:
- LIGHTING / COLOR GRADE (type: "lighting"): One clip has a noticeably warmer/cooler, brighter/darker, or differently graded tone than the majority
- ATMOSPHERE (type: "atmosphere"): One clip shows different weather, time of day, season, or environmental conditions than the others
- STYLE MISMATCH (type: "other"): One clip looks like it came from a different AI model or style — different sharpness, grain, rendering quality, or overall aesthetic

Rules:
- Compare each shot against the OVERALL PATTERN of the full sequence, not just its neighbors
- Only flag clips with clear, significant differences that would be noticeable on a cut
- Minor lighting angle shifts or color variation are expected — flag only jarring mismatches
- If the sequence is consistent, return {"outliers": []}
- Reference shots by the number in their label (Shot 1 → shot_index 0, Shot 2 → shot_index 1, etc.)

For each outlier return:
- shot_index: 0-based index of the outlier shot
- type: "lighting" | "atmosphere" | "other"
- description: one sentence — what is different about this clip vs. the others
- fix_suggestion: one imperative instruction (e.g. "Regrade this clip to match the warm golden-hour tone of the surrounding shots" or "Change the sky to overcast to match the rest of the sequence")
- severity: "low" | "medium" | "high"

Return STRICT JSON only:
{"outliers": [{"shot_index": 0, "type": "...", "description": "...", "fix_suggestion": "...", "severity": "..."}]}

If all consistent: {"outliers": []}"""


def build_holistic_prompt(user_hint: str = "") -> str:
    hint = (user_hint or "").strip()
    if not hint:
        return HOLISTIC_PROMPT
    return (
        "USER HINT — the person who uploaded this footage said:\n"
        f'  "{hint}"\n\n'
        "Use this hint to focus your review on the specific consistency issue they described.\n\n"
        + HOLISTIC_PROMPT
    )


_ADD_VERBS = ("add", "place", "put", "insert", "restore", "bring back", "return", "reintroduce")
_REMOVE_VERBS = ("remove", "erase", "delete", "hide")
_TRANSFORM_VERBS = (
    "regrade", "change", "adjust", "shift", "match", "apply",
    "convert", "alter", "transform", "make", "update", "fix",
    "correct", "modify", "replace the lighting", "replace the atmosphere",
)
_ALT_CUTS = (
    " or replace",
    " or substitute",
    " or swap",
    " in post-production",
    " in post production",
    "; replace",
)


def _strip_alternatives(s: str) -> str:
    """Trim 'or replace with X' / 'in post-production' tails so we keep a clean imperative."""
    s = s.strip().rstrip(".")
    low = s.lower()
    for cut in _ALT_CUTS:
        idx = low.find(cut)
        if idx > 0:
            s = s[:idx]
            low = s.lower()
    return s.rstrip(" ,")


def _starts_with_remove_verb(s: str) -> bool:
    low = s.lower()
    return any(low.startswith(v + " ") for v in _REMOVE_VERBS)


def _starts_with_add_verb(s: str) -> bool:
    low = s.lower()
    return any(low.startswith(v + " ") for v in _ADD_VERBS)


def _is_transform_instruction(s: str) -> bool:
    """Returns True when the string is a whole-clip transformation instruction
    (e.g. 'Regrade this clip to match...') rather than a replacement description
    (e.g. 'a wooden goblet' or 'empty table surface')."""
    low = s.lower().lstrip()
    return any(low.startswith(v + " ") or low.startswith(v + " the ") for v in _TRANSFORM_VERBS)


def _extract_object(imperative: str) -> str:
    """From 'Remove the coffee cup from the table' → 'the coffee cup'."""
    s = imperative.strip().rstrip(".")
    for verb in _REMOVE_VERBS:
        if s.lower().startswith(verb + " "):
            s = s[len(verb):].strip()
            break
    for cut in (" from the ", " from ", " on the ", " on ",
                " in the ", " in ", " at the ", " at "):
        idx = s.lower().find(cut)
        if idx > 0:
            s = s[:idx]
            break
    return s.strip() or "the unwanted object"


def build_aleph_prompt(
    error: dict,
    has_marker: bool = False,
    in_video_marker: bool = False,
) -> str:
    """
    Build a short, direct Aleph imperative.

    - in_video_marker=True: a red rectangle is burned into every frame of
      the input clip. Strongest spatial signal. The prompt tells Aleph to
      remove what's inside that on-screen rectangle along with the rectangle
      itself.
    - has_marker=True (legacy): a separate reference image is provided via
      Aleph's `references` array. Weaker than in-video — Aleph may ignore it.
    - Both False: text-only prompt.
    - Whole-clip transforms (lighting, atmosphere, style): when replaceWith is
      a transformation instruction, use it directly — no marker needed.
    """
    fix_mode = (error.get("fixMode") or "remove").lower()

    # Whole-clip transformation: lighting/atmosphere/style fix where replaceWith
    # is already a full imperative instruction (e.g. "Regrade this clip to match
    # the warm golden-hour tone of the surrounding shots"). Use it directly.
    if fix_mode == "replace":
        replace_with = (error.get("replaceWith") or "").strip().rstrip(".")
        if replace_with and _is_transform_instruction(replace_with):
            base = replace_with.rstrip(".")
            ref_clause = (
                " Use the reference image as the visual target for the correct look."
                if has_marker else ""
            )
            return (
                base + "." + ref_clause + " "
                "Apply this change uniformly to every frame of the clip "
                "from the very first frame to the very last — do not fade, "
                "revert, or apply it to only part of the clip duration."
            )

    if in_video_marker:
        replace_with = (error.get("replaceWith") or "").strip().rstrip(".")
        err_type = (error.get("type") or "").lower()
        is_wardrobe_type = err_type in ("wardrobe", "hair")

        is_set_dressing_type = err_type in ("set_dressing", "prop")

        if fix_mode == "replace" and replace_with:
            if is_wardrobe_type:
                # Wardrobe/hair: restore the original item without affecting anything
                # else. The fixSuggestion is already a clean imperative so use it
                # directly, then constrain Aleph to only touch the red-boxed region.
                return (
                    f"In this video there is a red rectangle drawn on the screen "
                    f"marking a wardrobe inconsistency to correct. "
                    f"{replace_with}. "
                    f"Only change the clothing or hair item inside the red rectangle — "
                    f"do not alter the actor's face, pose, skin, or any other part of "
                    f"the scene. Remove the red rectangle. The result must look "
                    f"natural and seamless, as if the item was always correct."
                )
            if is_set_dressing_type and _starts_with_add_verb(replace_with):
                # Object is missing from this shot and needs to be added — the red
                # rectangle marks WHERE it should appear, not something to replace.
                return (
                    f"In this video there is a red rectangle drawn on the screen "
                    f"marking a location where an object is missing. "
                    f"{replace_with}. "
                    f"Place the object naturally inside the red rectangle area, "
                    f"matching the scene's existing lighting, shadows, and perspective. "
                    f"Remove the red rectangle. The result must look as if the object "
                    f"was always there."
                )
            return (
                f"In this video there is a red rectangle drawn on the screen. "
                f"Replace the object inside the red rectangle with {replace_with}. "
                f"Remove the red rectangle entirely. The final video must show "
                f"no rectangle and no original object — only {replace_with} in "
                f"that location, blending naturally with the surroundings."
            )
        return (
            "In this video there is a red rectangle drawn on the screen. "
            "Remove BOTH the red rectangle AND the object inside it. "
            "Fill the entire rectangle region with the surrounding background "
            "(table surface, wall, whatever is naturally behind it). The final "
            "video must show no rectangle and no object inside it — completely "
            "clean as if neither was ever there."
        )

    fix_mode = (error.get("fixMode") or "remove").lower()
    raw_fix = (error.get("fixSuggestion") or "").strip()
    fix = _strip_alternatives(raw_fix)
    description = (error.get("description") or "").strip().rstrip(".")

    obj_phrase = (
        _extract_object(fix)
        if _starts_with_remove_verb(fix)
        else (description or "the unwanted object")
    )

    if fix_mode == "replace":
        replace_with = (error.get("replaceWith") or "").strip().rstrip(".")
        if not replace_with:
            # User toggled replace but didn't say what — safer to remove
            # rather than let Aleph improvise.
            return _build_remove_prompt(fix, obj_phrase, has_marker)
        if has_marker:
            return (
                f"Replace the object outlined in red in the @marker reference "
                f"with {replace_with}. The replacement should match the scene's "
                f"lighting and surroundings."
            )
        return f"Replace {obj_phrase} with {replace_with}."

    return _build_remove_prompt(fix, obj_phrase, has_marker)


def _build_remove_prompt(fix: str, obj_phrase: str, has_marker: bool) -> str:
    if has_marker:
        return (
            f"Remove the object outlined in red in the @marker reference. "
            f"Fill the empty space with the surrounding table surface and "
            f"background. {obj_phrase.capitalize()} should not be visible in "
            f"any frame."
        )
    if _starts_with_remove_verb(fix):
        return f"{fix}. Fill the empty space with the surrounding background."
    if fix:
        return f"Remove {fix}. Fill the empty space with the surrounding background."
    return (
        f"Remove {obj_phrase}. Fill the empty space with the surrounding background."
    )


def compute_continuity_score(errors: list) -> int:
    high_count = sum(1 for e in errors if e.get("severity") == "high")
    score = max(0, 100 - (len(errors) * 8) - (high_count * 5))
    return score
